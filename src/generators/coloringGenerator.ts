export function generateColoring(subject: string): ColoringData {
  const key = Object.keys(coloringTemplates).find(k => subject.toLowerCase().includes(k)) || 'turtle';
  const template = coloringTemplates[key];

  const title = `Color the ${key.charAt(0).toUpperCase() + key.slice(1)}!`;

  return {
    subject: key,
    svgPaths: template.paths,
    viewBox: template.viewBox,
    title,
  };
}
